// The recon map's geography: the lower 48, Alaska and Hawaii as real outlines (longitude, latitude),
// projected (Albers equal-area, the usual US map projection) into the map's 440x290 view, with Alaska and
// Hawaii in their inset boxes. The pins for the bosses' cities come out of the same projection, so they
// sit where the cities are.

type LonLat = [number, number];
export interface XY { x: number; y: number }

const RAD = Math.PI / 180;
const albers = (lat1: number, lat2: number, lat0: number, lon0: number) => {
  const n = (Math.sin(lat1 * RAD) + Math.sin(lat2 * RAD)) / 2;
  const C = Math.cos(lat1 * RAD) ** 2 + 2 * n * Math.sin(lat1 * RAD);
  const rho0 = Math.sqrt(C - 2 * n * Math.sin(lat0 * RAD)) / n;
  return ([lon, lat]: LonLat) => {
    const rho = Math.sqrt(C - 2 * n * Math.sin(lat * RAD)) / n;
    const th = n * (lon - lon0) * RAD;
    return { x: rho * Math.sin(th), y: -(rho0 - rho * Math.cos(th)) };
  };
};

/** Fit a projection's shapes into a box: returns the projector into view coordinates. */
const fitted = (proj: (p: LonLat) => XY, shapes: LonLat[][], box: { x: number; y: number; w: number; h: number }) => {
  let x0 = Infinity, y0 = Infinity, x1 = -Infinity, y1 = -Infinity;
  for (const s of shapes) for (const p of s) { const q = proj(p); x0 = Math.min(x0, q.x); x1 = Math.max(x1, q.x); y0 = Math.min(y0, q.y); y1 = Math.max(y1, q.y); }
  const k = Math.min(box.w / (x1 - x0), box.h / (y1 - y0));
  const ox = box.x + (box.w - (x1 - x0) * k) / 2, oy = box.y + (box.h - (y1 - y0) * k) / 2;
  return (p: LonLat): XY => { const q = proj(p); return { x: ox + (q.x - x0) * k, y: oy + (q.y - y0) * k }; };
};

